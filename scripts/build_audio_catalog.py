"""Offline operator-only catalog builder. Does not play/export audio or touch saves."""
import argparse,hashlib,json,struct
from pathlib import Path
import UnityPy


def build(data,output,audit):
    env=UnityPy.load(str(data/'resources.assets')); clips={}
    core={8594:('first_trumpet','퍼스트 트럼펫','warning_music'),8813:('second_trumpet','세컨드 트럼펫','warning_music'),9136:('third_trumpet','서드 트럼펫','warning_music'),9281:('qliphoth_meltdown','클리포트 폭주 알림음','warning_sound')}
    # Validate serialized playback references, not just suggestive resource names.
    level=UnityPy.load(str(data/'level2')); bgm=next(o for o in level.objects if o.path_id==36337); energy=next(o for o in level.objects if o.path_id==37584)
    b=bgm.get_raw_data();pos=32;lists=[]
    for _ in range(4):
        n=struct.unpack_from('<i',b,pos)[0];pos+=4
        assert 0<n<100
        refs=[struct.unpack_from('<iq',b,pos+i*12) for i in range(n)];pos+=n*12+4;lists.append(refs)
    assert lists[1:]==[[(3,8594)],[(3,8813)],[(3,9136)]]
    assert struct.unpack_from('<iq',energy.get_raw_data(),676)==(3,9281)
    evidence=[]; ambiguous=set()
    with (data/'resources.resource').open('rb') as stream:
        for o in env.objects:
            if o.type.name!='AudioClip':continue
            t=o.read_typetree();r=t['m_Resource'];assert Path(r['m_Source']).name=='resources.resource'
            stream.seek(r['m_Offset']);raw=stream.read(r['m_Size']);assert len(raw)==r['m_Size']
            sha=hashlib.sha256(raw).hexdigest();name=t['m_Name'];freq=t['m_Frequency'];channels=t['m_Channels'];length=t['m_Length']
            key=f'{name}|{freq}|{channels}'
            identity,label,category=core.get(o.path_id,('sound_'+sha[:24],'구분된 소리 '+sha[:8],'unclassified_sound'))
            entry=dict(key=key,length=length,sound_id=identity,label=label,category=category,asset_sha256=sha)
            if key in clips and clips[key]!=entry: ambiguous.add(key)
            clips[key]=entry;evidence.append(dict(path_id=o.path_id,**entry))
    for key in ambiguous: del clips[key]
    assert all(any(e['sound_id']==x[0] for e in clips.values()) for x in core.values())
    output.parent.mkdir(parents=True,exist_ok=True)
    fingerprints={}
    for filename in ('resources.assets','resources.resource','level2'):
        with (data/filename).open('rb') as handle:
            fingerprints[filename]=hashlib.file_digest(handle,'sha256').hexdigest()
    header='// Generated by scripts/build_audio_catalog.py. Metadata only; no audio payload.\nusing System;\nusing System.IO;\nusing System.Security.Cryptography;\nusing System.Collections.Generic;\nusing UnityEngine;\npublic static class ConsoleSoundCatalog {\n'
    header+='static bool verified;\npublic static void Initialize(string data) { verified=false; try { using(var sha=SHA256.Create()) {\n'
    q=lambda x:json.dumps(x,ensure_ascii=False)
    for filename,sha in fingerprints.items():
        header+='using(var f=File.OpenRead(Path.Combine(data,'+q(filename)+'))) { if(BitConverter.ToString(sha.ComputeHash(f)).Replace("-","").ToLowerInvariant()!='+q(sha)+') return; }\n'
    header+='} verified=true; } catch { /* Keep anonymous observation available. */ } }\n'
    header+='public sealed class Entry { public float length; public string id,label,category; public Entry(float n,string i,string l,string c){length=n;id=i;label=l;category=c;} }\n'
    header+='static readonly Dictionary<string,Entry> entries=new Dictionary<string,Entry> {\n'
    q=lambda x:json.dumps(x,ensure_ascii=False)
    for e in clips.values():header+='{'+q(e['key'])+',new Entry('+format(e['length'],'.9g')+'f,'+q(e['sound_id'])+','+q(e['label'])+','+q(e['category'])+')},\n'
    header+='};\npublic static Entry Match(AudioClip clip) { Entry value; if(verified && clip!=null && entries.TryGetValue(clip.name+"|"+clip.frequency+"|"+clip.channels,out value) && Math.Abs(value.length-clip.length)<.002f) return value; return null; }\n}\n'
    output.write_text(header,encoding='utf-8');audit.write_text(json.dumps({'asset_fingerprints':fingerprints,'ambiguous_keys':sorted(ambiguous),'assembly_sha256':hashlib.sha256((data/'Managed/Assembly-CSharp.dll').read_bytes()).hexdigest(),'bgm_refs':lists,'overload_ref':[3,9281],'clips':evidence},ensure_ascii=False,indent=2),encoding='utf-8')
    print(json.dumps({'catalog_entries':len(clips),'named':len(core),'output':str(output)}))

if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--data',type=Path,required=True);p.add_argument('--output',type=Path,required=True);p.add_argument('--audit',type=Path,required=True);a=p.parse_args();build(a.data,a.output,a.audit)
